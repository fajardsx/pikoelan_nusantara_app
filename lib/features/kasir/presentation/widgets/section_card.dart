      child: Column(
        crossAxisAlignment: CrossAxisAlignment.start,
        children: [
          Text(
            title,
            style: const TextStyle(
              fontSize: 15,
              fontWeight: FontWeight.bold,
              color: RestaurantColors.textPrimary,
            ),
          ),
          const SizedBox(height: 14),
          child,
        ],
      ),
